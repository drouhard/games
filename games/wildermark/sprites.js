/* Pixel art for the Wildermark.

   One sixteen-colour palette for everything: creatures, wardens, land art and
   the pips that stand on the overworld map. The ramp is built around the five
   colours of the game, so a card, the monster it depicts and the terrain it
   comes from all sit in the same handful of hues and read as one world.

   Symmetric things are authored as a `half` - the left eight columns - and
   mirrored on load, which is half the typing and comes out actually
   symmetric. Beasts and landscapes read far better asymmetric, so those give
   full 16-wide `rows`.

   Row widths and palette characters are checked by tools/check-sprites.mjs,
   because a miscounted row silently clips the art and that is a miserable
   thing to debug from a screenshot. */

